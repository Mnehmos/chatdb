import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { appEventNames, knownEventPayloads, typeDefs } from '../contracts/loop_events.contract.mjs';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tsOut = path.join(repoRoot, 'src', 'types', 'generated', 'loopEvents.ts');
const rustOut = path.join(repoRoot, 'src-tauri', 'src', 'contracts', 'loop_events.rs');

const rustKeywords = new Set([
  'as', 'break', 'const', 'continue', 'crate', 'else', 'enum', 'extern', 'false',
  'fn', 'for', 'if', 'impl', 'in', 'let', 'loop', 'match', 'mod', 'move', 'mut',
  'pub', 'ref', 'return', 'self', 'Self', 'static', 'struct', 'super', 'trait',
  'true', 'type', 'unsafe', 'use', 'where', 'while', 'async', 'await', 'dyn',
  'abstract', 'become', 'box', 'do', 'final', 'macro', 'override', 'priv', 'typeof',
  'unsized', 'virtual', 'yield', 'try',
]);

function mkdirFor(file) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
}

function toPascalCase(value) {
  return String(value)
    .replace(/[^a-zA-Z0-9]+/g, ' ')
    .split(' ')
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('') || 'Value';
}

function rustFieldName(name) {
  return rustKeywords.has(name) ? `${name}_` : name;
}

function isPrimitive(name) {
  return ['string', 'int', 'float', 'boolean', 'json'].includes(name);
}

function normalizeField(definition) {
  if (typeof definition === 'string') {
    return { type: definition, optional: false };
  }
  return definition;
}

function renderTsTypeRef(typeName) {
  switch (typeName) {
    case 'string':
      return 'string';
    case 'int':
    case 'float':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'json':
      return 'unknown';
    default:
      return typeName;
  }
}

function renderTsFieldType(definition) {
  const field = normalizeField(definition);
  if (field.type === 'array') {
    return `${renderTsFieldType(field.item)}[]`;
  }
  return renderTsTypeRef(field.type);
}

function renderRustTypeRef(typeName) {
  switch (typeName) {
    case 'string':
      return 'String';
    case 'int':
      return 'u32';
    case 'float':
      return 'f64';
    case 'boolean':
      return 'bool';
    case 'json':
      return 'serde_json::Value';
    default:
      return typeName;
  }
}

function renderRustFieldType(definition) {
  const field = normalizeField(definition);
  const inner = field.type === 'array'
    ? `Vec<${renderRustFieldType(field.item)}>`
    : renderRustTypeRef(field.type);
  return field.optional ? `Option<${inner}>` : inner;
}

function renderTsType(name, spec) {
  if (spec.kind === 'union') {
    return `export type ${name} = ${spec.values.map((value) => `'${value}'`).join(' | ')};\n`;
  }

  if (spec.kind === 'object') {
    const lines = Object.entries(spec.fields).map(([fieldName, fieldSpec]) => {
      const normalized = normalizeField(fieldSpec);
      const optional = normalized.optional ? '?' : '';
      return `  ${fieldName}${optional}: ${renderTsFieldType(normalized)};`;
    });
    if (spec.open) {
      lines.push('  [key: string]: unknown;');
    }
    return `export interface ${name} {\n${lines.join('\n')}\n}\n`;
  }

  throw new Error(`Unsupported TS spec kind for ${name}: ${spec.kind}`);
}

function renderRustType(name, spec) {
  if (spec.kind === 'union') {
    const variants = spec.values.map((value) => {
      const variant = toPascalCase(value);
      return `    #[serde(rename = "${value}")]\n    ${variant},`;
    }).join('\n');
    return `#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]\npub enum ${name} {\n${variants}\n}\n`;
  }

  if (spec.kind === 'object') {
    const fields = Object.entries(spec.fields).map(([fieldName, fieldSpec]) => {
      const normalized = normalizeField(fieldSpec);
      const rustName = rustFieldName(fieldName);
      const attrs = [];
      if (rustName !== fieldName) {
        attrs.push(`    #[serde(rename = "${fieldName}")]`);
      }
      if (normalized.optional) {
        attrs.push('    #[serde(skip_serializing_if = "Option::is_none")]');
      }
      attrs.push(`    pub ${rustName}: ${renderRustFieldType(normalized)},`);
      return attrs.join('\n');
    });

    if (spec.open) {
      fields.push('    #[serde(flatten)]');
      fields.push('    pub extra: BTreeMap<String, serde_json::Value>,');
    }

    return `#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]\npub struct ${name} {\n${fields.join('\n')}\n}\n`;
  }

  throw new Error(`Unsupported Rust spec kind for ${name}: ${spec.kind}`);
}

function renderTsFile() {
  const header = `// Generated by scripts/generate-loop-event-contracts.mjs.\n// Do not edit manually.\n\n`;
  const typeBlocks = Object.entries(typeDefs).map(([name, spec]) => renderTsType(name, spec)).join('\n');
  const knownNames = Object.keys(knownEventPayloads);
  const knownMap = knownNames
    .map((eventName) => `  '${eventName}': ${knownEventPayloads[eventName]};`)
    .join('\n');
  const appNamesUnion = appEventNames.map((name) => `  | '${name}'`).join('\n');

  return `${header}${typeBlocks}
export interface LoopEventPayloadMap {
${knownMap}
}

export type KnownLoopEventName = keyof LoopEventPayloadMap;
export type KnownLoopEvent<K extends KnownLoopEventName = KnownLoopEventName> = {
  [T in K]: { type: T; payload: LoopEventPayloadMap[T] }
}[K];

export type AppLoopEventName =
${appNamesUnion};

export type AppLoopEvent = KnownLoopEvent<AppLoopEventName>;
`;
}

function renderRustFile() {
  const header = `// Generated by scripts/generate-loop-event-contracts.mjs.\n// Do not edit manually.\n\nuse serde::{Deserialize, Serialize};\nuse std::collections::BTreeMap;\n\n`;
  const typeBlocks = Object.entries(typeDefs).map(([name, spec]) => renderRustType(name, spec)).join('\n');
  return `${header}${typeBlocks}`;
}

mkdirFor(tsOut);
mkdirFor(rustOut);

fs.writeFileSync(tsOut, renderTsFile(), 'utf8');
fs.writeFileSync(rustOut, renderRustFile(), 'utf8');

console.log(`Wrote ${path.relative(repoRoot, tsOut)}`);
console.log(`Wrote ${path.relative(repoRoot, rustOut)}`);
